"""
distill_tasks.py

Phase 2 of the contracts dataset: tasks that need judgment, not just
extraction, so they're generated by prompting a strong model (Claude) over
REAL clause text pulled from CUAD. This is standard distillation practice —
the *input* clause is always real, only the target explanation/summary/draft
is model-generated. Every example is tagged with its source so provenance
stays traceable, and you should spot-check a sample before training on it.

Requires: an Anthropic API key.
    export ANTHROPIC_API_KEY=sk-ant-...
    pip install anthropic --break-system-packages

Usage:
    python distill_tasks.py --cuad data/CUADv1.json --out-dir output/ \
        --n-per-task 500 --model claude-sonnet-4-6

Cost note: each example is 1 API call. Start with --n-per-task 50 to sanity
check output quality and estimate cost before running the full batch.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import time
from pathlib import Path

random.seed(13)

try:
    import anthropic
except ImportError:
    anthropic = None


# ---------------------------------------------------------------------------
# Task definitions: each maps a real clause -> a system prompt that asks
# Claude to generate the target output. Keep these prompts narrow and
# specific — vague prompts produce generic, low-signal training targets.
# ---------------------------------------------------------------------------
TASK_PROMPTS = {
    "clause_summarization": {
        "system": (
            "You summarize contract clauses in plain English for a non-lawyer business "
            "reader. One to two sentences. No legal jargon. State the practical effect, "
            "not the legal theory."
        ),
        "user_template": (
            'Summarize this {category} clause from a {ctype} in plain English:\n\n"{text}"'
        ),
        "instruction_for_model_input": 'Summarize the following {category} clause in plain English:\n\n"{text}"',
    },
    "clause_drafting": {
        "system": (
            "You draft contract clauses in standard commercial legal style, modeled on "
            "real market-standard language. Output ONLY the clause text, no commentary."
        ),
        "user_template": (
            "Here is a real {category} clause from a {ctype} as a style reference:\n\n"
            '"{text}"\n\n'
            "Draft a NEW, original {category} clause for a different {ctype}, in a similar "
            "level of formality and market-standard structure, but with different specific "
            "terms (different notice periods, different party names as [Party A]/[Party B], etc). "
            "Output only the clause."
        ),
        "instruction_for_model_input": "Draft a {category} clause for a {ctype} between [Party A] and [Party B].",
    },
    "risk_flagging": {
        "system": (
            "You are a contract risk-review assistant. Given a clause, identify whether it "
            "is one-sided, non-market, or otherwise worth flagging for negotiation — or state "
            "that it looks like standard market language. Be specific about WHY, citing the "
            "exact language. Two to four sentences."
        ),
        "user_template": (
            'Review this {category} clause from a {ctype} for negotiation risk:\n\n"{text}"'
        ),
        "instruction_for_model_input": 'Review this {category} clause for negotiation risk:\n\n"{text}"',
    },
    "negotiation_counter": {
        "system": (
            "You are a contract negotiation assistant representing the counterparty. Given a "
            "clause, propose a specific, concrete counter-proposal or redline that would make "
            "the term more balanced. Output the revised clause language, not general advice."
        ),
        "user_template": (
            "This {category} clause is in a {ctype} we're negotiating. Propose a more balanced "
            'counter-draft:\n\n"{text}"'
        ),
        "instruction_for_model_input": 'Propose a more balanced counter-draft for this {category} clause:\n\n"{text}"',
    },
}


def sample_real_clauses(cuad_path: str | Path, n: int) -> list[dict]:
    """Pull a random sample of REAL, answered clauses from CUAD to use as
    grounding input for distillation."""
    raw = json.loads(Path(cuad_path).read_text())
    pool = []
    for contract in raw["data"]:
        title = contract["title"]
        for para in contract["paragraphs"]:
            for qa in para["qas"]:
                if qa["is_impossible"] or not qa.get("answers"):
                    continue
                category = qa["id"].split("__")[-1]
                if category in {"Document Name", "Parties", "Agreement Date", "Effective Date"}:
                    continue  # metadata fields, not substantive clauses
                pool.append(
                    {
                        "contract_title": title,
                        "category": category,
                        "text": qa["answers"][0]["text"].strip(),
                    }
                )
    random.shuffle(pool)
    return pool[:n]


def call_claude(client, model: str, system: str, user: str, max_retries: int = 3) -> str:
    for attempt in range(max_retries):
        try:
            resp = client.messages.create(
                model=model,
                max_tokens=500,
                system=system,
                messages=[{"role": "user", "content": user}],
            )
            return "".join(b.text for b in resp.content if b.type == "text").strip()
        except Exception:
            if attempt == max_retries - 1:
                raise
            time.sleep(2**attempt)
    raise RuntimeError("unreachable")


def build_task_examples(client, model: str, task_name: str, clauses: list[dict]) -> list[dict]:
    spec = TASK_PROMPTS[task_name]
    examples = []
    for i, c in enumerate(clauses):
        ctype = "commercial agreement"  # CUAD titles vary too much to reliably splice here; keep generic
        user_prompt = spec["user_template"].format(
            category=c["category"], text=c["text"], ctype=ctype
        )
        try:
            target = call_claude(client, model, spec["system"], user_prompt)
        except Exception as e:
            print(f"  [{task_name}] skipping example {i} after repeated errors: {e}")
            continue
        model_input = spec["instruction_for_model_input"].format(
            category=c["category"], text=c["text"], ctype=ctype
        )
        examples.append(
            {
                "task": task_name,
                "messages": [
                    {"role": "system", "content": spec["system"]},
                    {"role": "user", "content": model_input},
                    {"role": "assistant", "content": target},
                ],
                "meta": {
                    "contract_title": c["contract_title"],
                    "category": c["category"],
                    "source_clause": "real (CUAD v1)",
                    "target_text": "distilled (Claude-generated)",
                },
            }
        )
        if (i + 1) % 25 == 0:
            print(f"  [{task_name}] {i + 1}/{len(clauses)}")
    return examples


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cuad", default="data/CUADv1.json")
    ap.add_argument("--out-dir", default="output")
    ap.add_argument(
        "--n-per-task",
        type=int,
        default=50,
        help="Start small (~50) to sanity-check before scaling up",
    )
    ap.add_argument("--model", default="claude-sonnet-4-6")
    ap.add_argument("--tasks", nargs="+", default=list(TASK_PROMPTS.keys()))
    args = ap.parse_args()

    if anthropic is None:
        raise SystemExit("Run: pip install anthropic --break-system-packages")
    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        raise SystemExit("Set ANTHROPIC_API_KEY in your environment first.")
    client = anthropic.Anthropic(api_key=api_key)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    for task_name in args.tasks:
        clauses = sample_real_clauses(args.cuad, args.n_per_task)
        print(f"Generating {len(clauses)} examples for {task_name}...")
        examples = build_task_examples(client, args.model, task_name, clauses)
        out_path = out_dir / f"{task_name}.jsonl"
        with out_path.open("w") as f:
            for ex in examples:
                f.write(json.dumps(ex) + "\n")
        print(f"  -> wrote {len(examples)} examples to {out_path}")


if __name__ == "__main__":
    main()
