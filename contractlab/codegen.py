from __future__ import annotations

import pprint
from pathlib import Path

import nbformat

from contractlab.config import TrainingConfig


def generated_script(config: TrainingConfig) -> str:
    values = pprint.pformat(config.to_dict(), sort_dicts=False, width=100)
    return f'''"""Generated by AI-Enabled Contracts Lab. Edit the configuration, then run this file."""

from contractlab.config import TrainingConfig
from contractlab.training import run_training

# Every field below is also available in the Train page.
CONFIG = {values}

config = TrainingConfig(**CONFIG)
errors = config.validate()
if errors:
    raise ValueError(" ".join(errors))

# run_training contains the explicit PyTorch forward/backward/update loop.
results = run_training(config)
print(results["test_metrics"])
'''


def generated_notebook(config: TrainingConfig) -> nbformat.NotebookNode:
    notebook = nbformat.v4.new_notebook()
    notebook["metadata"]["kernelspec"] = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    notebook["cells"] = [
        nbformat.v4.new_markdown_cell(
            "# AI-Enabled Contracts Lab clause-classification experiment\n\n"
            "This notebook reproduces the workbench configuration using the same visible PyTorch pipeline."
        ),
        nbformat.v4.new_markdown_cell(
            "## 1. Configuration\n\n"
            "The learning rate controls update size; batch size controls examples per forward pass; "
            "gradient accumulation creates a larger effective batch without requiring the same VRAM."
        ),
        nbformat.v4.new_code_cell(
            "from contractlab.config import TrainingConfig\n"
            f"config = TrainingConfig(**{pprint.pformat(config.to_dict(), sort_dicts=False, width=100)})\n"
            "config"
        ),
        nbformat.v4.new_markdown_cell(
            "## 2. Inspect and split the data\n\n"
            "We split by `contract_id`, because clauses from the same agreement share wording and context."
        ),
        nbformat.v4.new_code_cell(
            "from contractlab.data import load_table, normalize_dataset, split_by_contract\n"
            "data = normalize_dataset(load_table(config.dataset_path))\n"
            "splits = split_by_contract(data, seed=config.seed)\n"
            "{name: (len(frame), frame['contract_id'].nunique()) for name, frame in splits.items()}"
        ),
        nbformat.v4.new_markdown_cell(
            "## 3. Train and evaluate\n\n"
            "Open `contractlab/training.py` beside this cell to follow the explicit optimizer loop."
        ),
        nbformat.v4.new_code_cell(
            "from contractlab.training import run_training\n"
            "results = run_training(config)\n"
            "results['test_metrics']"
        ),
    ]
    return notebook


def write_notebook(config: TrainingConfig, output: str | Path) -> Path:
    target = Path(output)
    target.parent.mkdir(parents=True, exist_ok=True)
    nbformat.write(generated_notebook(config), target)
    return target
